# Native Permutation and Group classes
class NativePermutation:
    """Native permutation implementation without SymPy."""
    def __init__(self, cycle_or_list):
        if isinstance(cycle_or_list, (list, tuple)):
            self._perm = list(cycle_or_list)
        else:
            self._perm = list(cycle_or_list)
        self._size = len(self._perm)

    def __call__(self, i):
        """Apply permutation to element i."""
        return self._perm[i]

    def __mul__(self, other):
        """Compose permutations."""
        if isinstance(other, NativePermutation):
            result = [self._perm[other._perm[i]] for i in range(self._size)]
            return NativePermutation(result)
        return NotImplemented

    def order(self):
        """Compute order of permutation (smallest n such that sigma^n = identity)."""
        identity = list(range(self._size))
        current = self._perm[:]
        n = 1
        while current != identity:
            current = [self._perm[current[i]] for i in range(self._size)]
            n += 1
            if n > self._size * 10:  # Safety limit
                break
        return n

    def __repr__(self):
        return f"Permutation({self._perm})"


class NativePermutationGroup:
    """Native permutation group implementation."""
    def __init__(self, generators):
        self.generators = list(generators)
        self._order = None
        self._is_abelian = None
        self._is_cyclic = None

    @property
    def is_abelian(self):
        """Check if group is abelian (commutative)."""
        if self._is_abelian is None:
            # Check if all generators commute
            for i, g1 in enumerate(self.generators):
                for g2 in self.generators[i+1:]:
                    if (g1 * g2)._perm != (g2 * g1)._perm:
                        self._is_abelian = False
                        return False
            self._is_abelian = True
        return self._is_abelian

    @property
    def is_cyclic(self):
        """Check if group is cyclic (generated by single element)."""
        if self._is_cyclic is None:
            # Check if there's a single generator whose order equals group order
            for gen in self.generators:
                if gen.order() == self.order():
                    self._is_cyclic = True
                    return True
            self._is_cyclic = len(self.generators) == 1
        return self._is_cyclic

    def order(self):
        """Compute order of group."""
        if self._order is None:
            # For small groups, enumerate elements
            # This is a simplified implementation
            self._order = 1
            for gen in self.generators:
                self._order *= gen.order()  # Upper bound
        return self._order


def SymmetricGroup(n):
    """Create symmetric group S_n (native implementation)."""
    # Generate all permutations of n elements
    identity = list(range(n))
    # Use two standard generators: (0 1) and (0 1 2 ... n-1)
    gen1 = list(range(n))
    gen1[0], gen1[1] = gen1[1], gen1[0]  # Transposition (0 1)

    gen2 = list(range(1, n)) + [0]  # Cycle (0 1 2 ... n-1)

    return NativePermutationGroup([NativePermutation(gen1), NativePermutation(gen2)])


def AlternatingGroup(n):
    """Create alternating group A_n (native implementation)."""
    # A_n is generated by 3-cycles
    if n < 3:
        return NativePermutationGroup([NativePermutation(list(range(n)))])
    gen = list(range(n))
    gen[0], gen[1], gen[2] = gen[1], gen[2], gen[0]  # 3-cycle (0 1 2)
    return NativePermutationGroup([NativePermutation(gen)])


def CyclicGroup(n):
    """Create cyclic group Z_n (native implementation)."""
    gen = list(range(1, n)) + [0]  # Cycle (0 1 2 ... n-1)
    return NativePermutationGroup([NativePermutation(gen)])


def DihedralGroup(n):
    """Create dihedral group D_n (native implementation)."""
    # D_n is symmetries of regular n-gon
    # Generated by rotation r and reflection s
    rotation = list(range(1, n)) + [0]  # Rotation
    reflection = list(reversed(range(n)))  # Reflection

    return NativePermutationGroup([NativePermutation(rotation), NativePermutation(reflection)])


