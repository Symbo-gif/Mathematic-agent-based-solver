class StructureType(Enum):
    """Types of algebraic structures"""
    GROUP = "group"
    RING = "ring"
    FIELD = "field"
    IDEAL = "ideal"
    MODULE = "module"
    UNKNOWN = "unknown"


class GroupProperty(Enum):
    """Properties of groups"""
    ABELIAN = "abelian"
    CYCLIC = "cyclic"
    SIMPLE = "simple"
    SOLVABLE = "solvable"
    NILPOTENT = "nilpotent"
    PERFECT = "perfect"


@dataclass
class AlgebraicStructure:
    """
    Represents an algebraic structure with its properties.
    
    Attributes:
        name: Name or identifier of the structure
        structure_type: Type (group, ring, field, etc.)
        order: Order/size of the structure
        properties: Set of properties the structure satisfies
        generators: Generators of the structure
        is_finite: Whether the structure is finite
    """
    name: str
    structure_type: StructureType
    order: Optional[int] = None
    properties: Set[str] = field(default_factory=set)
    generators: List[Any] = field(default_factory=list)
    is_finite: bool = True
    
    def to_dict(self) -> Dict[str, Any]:
        """Serialize to dictionary"""
        return {
            'name': self.name,
            'type': self.structure_type.value,
            'order': self.order,
            'properties': list(self.properties),
            'generator_count': len(self.generators),
            'is_finite': self.is_finite
        }


@dataclass 
class IsomorphismResult:
    """Result of isomorphism check"""
    are_isomorphic: bool
    mapping: Optional[Dict[Any, Any]] = None
    reason: str = ""
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            'are_isomorphic': self.are_isomorphic,
            'has_mapping': self.mapping is not None,
            'reason': self.reason
        }


