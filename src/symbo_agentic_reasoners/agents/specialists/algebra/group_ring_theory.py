    def check_isomorphism(
        self,
        group1: PermutationGroup,
        group2: PermutationGroup
    ) -> IsomorphismResult:
        """
        Check if two groups are isomorphic.
        
        Args:
            group1: First group
            group2: Second group
            
        Returns:
            IsomorphismResult with determination and mapping if found
        """
        self.tasks_executed += 1
        self.isomorphisms_checked += 1
        
        try:
            # Quick check: same order
            order1 = group1.order()
            order2 = group2.order()
            
            if order1 != order2:
                self.tasks_succeeded += 1
                return IsomorphismResult(
                    are_isomorphic=False,
                    reason=f"Different orders: {order1} vs {order2}"
                )
            
            # Check structural properties
            if group1.is_abelian != group2.is_abelian:
                self.tasks_succeeded += 1
                return IsomorphismResult(
                    are_isomorphic=False,
                    reason="One is abelian, the other is not"
                )
            
            if group1.is_cyclic != group2.is_cyclic:
                self.tasks_succeeded += 1
                return IsomorphismResult(
                    are_isomorphic=False,
                    reason="One is cyclic, the other is not"
                )
            
            # Try to find isomorphism
            # For small groups, compare structure
            if order1 <= 100:
                # Compare via generators
                gen1_orders = sorted([g.order() for g in group1.generators])
                gen2_orders = sorted([g.order() for g in group2.generators])
                
                if gen1_orders == gen2_orders:
                    # Likely isomorphic (not proof, but strong indicator)
                    self.tasks_succeeded += 1
                    return IsomorphismResult(
                        are_isomorphic=True,
                        reason="Same order, properties, and generator structure"
                    )
            
            # Default: cannot determine
            self.tasks_succeeded += 1
            return IsomorphismResult(
                are_isomorphic=False,  # Conservative
                reason="Could not determine isomorphism"
            )
            
        except Exception as e:
            self.tasks_failed += 1
            logger.warning(f"Isomorphism check failed: {type(e).__name__}: {e}")
            return IsomorphismResult(
                are_isomorphic=False,
                reason=f"Error: {str(e)}"
            )
    
