    def create_group(
        self,
        group_type: str,
        n: int
    ) -> Tuple[Any, AlgebraicStructure]:
        """
        Create a named group and return its structure.
        
        Args:
            group_type: Type of group ('symmetric', 'alternating', 'cyclic', 'dihedral')
            n: Order parameter
            
        Returns:
            Tuple of (SymPy group object, AlgebraicStructure descriptor)
        """
        self.tasks_executed += 1
        
        try:
            if group_type == 'symmetric':
                group = SymmetricGroup(n)
                name = f"S_{n}"
                order = math.factorial(n)
            elif group_type == 'alternating':
                group = AlternatingGroup(n)
                name = f"A_{n}"
                order = math.factorial(n) // 2
            elif group_type == 'cyclic':
                group = CyclicGroup(n)
                name = f"Z_{n}"
                order = n
            elif group_type == 'dihedral':
                group = DihedralGroup(n)
                name = f"D_{n}"
                order = 2 * n
            else:
                raise ValueError(f"Unknown group type: {group_type}")

            # Analyze properties
            properties = self._analyze_group_properties(group)

            structure = AlgebraicStructure(
                name=name,
                structure_type=StructureType.GROUP,
                order=int(order) if order != float('inf') else None,
                properties=properties,
                generators=list(group.generators),
                is_finite=True
            )
            
            # Cache
            self.structure_catalog[name] = structure
            self.structures_classified += 1
            self.tasks_succeeded += 1
            
            return group, structure
            
        except Exception as e:
            self.tasks_failed += 1
            logger.warning(f"Group creation failed: {type(e).__name__}: {e}")
            raise
    
    def _analyze_group_properties(self, group: PermutationGroup) -> Set[str]:
        """Analyze and return properties of a permutation group"""
        properties = set()
        
        try:
            if group.is_abelian:
                properties.add(GroupProperty.ABELIAN.value)
            
            if group.is_cyclic:
                properties.add(GroupProperty.CYCLIC.value)
            
            if hasattr(group, 'is_solvable') and group.is_solvable:
                properties.add(GroupProperty.SOLVABLE.value)
            
            if hasattr(group, 'is_nilpotent') and group.is_nilpotent:
                properties.add(GroupProperty.NILPOTENT.value)
                
        except (AttributeError, TypeError) as e:
            logger.debug(f"Could not analyze all group properties: {e}")
        
        return properties
    
