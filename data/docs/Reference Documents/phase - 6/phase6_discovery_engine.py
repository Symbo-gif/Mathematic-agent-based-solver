class SandboxEvaluator:
    """
    Agent 3.2: Sandbox Evaluator
    
    Secure execution environment that runs proposed code against
    rigorous test sets.
    
    📚 Reference: Phase 6 must engineer the capacity for novel mathematical 
    discovery.docx, Section 3
    """
    
    def __init__(
        self, 
        problem_spec: ProblemSpecification,
        timeout_seconds: float = 5.0
    ):
        self.problem_spec = problem_spec
        self.timeout = timeout_seconds
        
    def evaluate(self, candidate: CodeCandidate) -> CodeCandidate:
        """
        Evaluate a code candidate in sandbox.
        
        Returns updated candidate with fitness scores.
        """
        start_time = time.time()
        
        try:
            # Write code to temp file
            with tempfile.NamedTemporaryFile(mode='w', suffix='.py', delete=False) as f:
                f.write(candidate.code)
                f.write(self._generate_test_harness())
                temp_path = f.name
            
            # Execute in subprocess (sandbox)
            result = subprocess.run(
                ['python', temp_path],
                capture_output=True,
                text=True,
                timeout=self.timeout
            )
            
            execution_time = (time.time() - start_time) * 1000
            candidate.execution_time_ms = execution_time
            
            # Parse results
            if result.returncode == 0:
                scores = self._parse_scores(result.stdout)
                candidate.correctness_score = scores.get('correctness', 0.0)
                candidate.fitness_score = self._compute_fitness(
                    scores, execution_time
                )
            else:
                candidate.fitness_score = 0.0
                candidate.correctness_score = 0.0
                
        except subprocess.TimeoutExpired:
            candidate.fitness_score = 0.0
            candidate.execution_time_ms = self.timeout * 1000
            
        except Exception as e:
            candidate.fitness_score = 0.0
            
        return candidate
    
    def _generate_test_harness(self) -> str:
        """Generate test harness code"""
        test_code = "\n\n# Test harness\n"
        test_code += "import json\n"
        test_code += "results = {'passed': 0, 'failed': 0, 'total': 0}\n"
        
        for i, (input_val, expected) in enumerate(self.problem_spec.test_cases):
            test_code += f"""
try:
    result = solve({repr(input_val)})
    if result == {repr(expected)}:
        results['passed'] += 1
    else:
        results['failed'] += 1
except:
    results['failed'] += 1
results['total'] += 1
"""
        
        test_code += "print(json.dumps(results))\n"
        return test_code
    
    def _parse_scores(self, stdout: str) -> Dict[str, float]:
        """Parse test results from stdout"""
        try:
            results = json.loads(stdout.strip().split('\n')[-1])
            correctness = results['passed'] / max(results['total'], 1)
            return {'correctness': correctness}
        except:
            return {'correctness': 0.0}
    
    def _compute_fitness(self, scores: Dict[str, float], execution_time: float) -> float:
        """Compute overall fitness score"""
        correctness = scores.get('correctness', 0.0)
        
        # Speed bonus (faster = better, up to 20% bonus)
        speed_bonus = max(0, 1.0 - execution_time / 1000) * 0.2
        
        # Final fitness
        fitness = correctness * 0.8 + speed_bonus
        
        return fitness


class HeuristicDistiller:
    """
    Agent 3.3: Heuristic Distiller
    
    Analyzes successful code to extract the underlying mathematical
    principle into human-readable form.
    
    📚 Reference: Phase 6 must engineer the capacity for novel mathematical 
    discovery.docx, Section 3
    """
    
    def __init__(self, llm_client=None):
        self.llm = llm_client
        
    def distill(self, successful_candidate: CodeCandidate) -> Dict[str, Any]:
        """
        Extract mathematical principle from successful code.
        
        Returns:
            Dictionary with prose explanation, formal spec, and applicable domains
        """
        # Analyze code structure
        analysis = self._analyze_code_structure(successful_candidate.code)
        
        # Extract key patterns
        patterns = self._extract_patterns(successful_candidate.code)
        
        # Generate prose explanation
        explanation = self._generate_explanation(analysis, patterns)
        
        # Identify applicable problem classes
        domains = self._identify_domains(analysis)
        
        return {
            'candidate_id': successful_candidate.candidate_id,
            'prose_explanation': explanation,
            'key_patterns': patterns,
            'algorithmic_class': analysis.get('class', 'unknown'),
            'applicable_domains': domains,
            'code': successful_candidate.code,
            'fitness_score': successful_candidate.fitness_score
        }
    
    def _analyze_code_structure(self, code: str) -> Dict[str, Any]:
        """Analyze code structure to identify algorithm type"""
        analysis = {
            'has_recursion': 'def ' in code and code.count('def ') > 1,
            'has_memoization': 'lru_cache' in code or 'memo' in code.lower(),
            'has_loops': 'for ' in code or 'while ' in code,
            'uses_sorting': 'sorted' in code or '.sort()' in code,
            'uses_max_min': 'max(' in code or 'min(' in code,
            'has_dp_table': '[[' in code and 'for ' in code,
        }
        
        # Classify algorithm
        if analysis['has_dp_table']:
            analysis['class'] = 'dynamic_programming'
        elif analysis['has_recursion'] and analysis['has_memoization']:
            analysis['class'] = 'memoized_recursion'
        elif analysis['uses_sorting'] and not analysis['has_dp_table']:
            analysis['class'] = 'greedy'
        elif analysis['has_loops'] and analysis['uses_max_min']:
            analysis['class'] = 'local_search'
        else:
            analysis['class'] = 'heuristic'
        
        return analysis
    
    def _extract_patterns(self, code: str) -> List[str]:
        """Extract key algorithmic patterns"""
        patterns = []
        
        if 'sorted(' in code:
            patterns.append("Sorting as preprocessing step")
        if 'max(' in code:
            patterns.append("Greedy maximum selection")
        if 'for i in range' in code:
            patterns.append("Linear iteration pattern")
        if 'while ' in code:
            patterns.append("Condition-based iteration")
        if 'dp[' in code or 'memo[' in code:
            patterns.append("Subproblem caching")
        if '+ 1' in code or '- 1' in code:
            patterns.append("Incremental update")
        
        return patterns
    
    def _generate_explanation(
        self, 
        analysis: Dict[str, Any], 
        patterns: List[str]
    ) -> str:
        """Generate prose explanation of the heuristic"""
        algo_class = analysis.get('class', 'unknown')
        
        explanation = f"This algorithm uses a {algo_class.replace('_', ' ')} approach. "
        
        if patterns:
            explanation += f"Key techniques include: {', '.join(patterns)}. "
        
        if algo_class == 'dynamic_programming':
            explanation += "It breaks the problem into overlapping subproblems and builds up solutions from smaller instances."
        elif algo_class == 'greedy':
            explanation += "It makes locally optimal choices at each step, hoping to find a global optimum."
        elif algo_class == 'memoized_recursion':
            explanation += "It combines recursive problem decomposition with result caching to avoid redundant computation."
        
        return explanation
    
    def _identify_domains(self, analysis: Dict[str, Any]) -> List[str]:
        """Identify problem domains where this heuristic applies"""
        domains = []
        
        algo_class = analysis.get('class', 'unknown')
        
        if algo_class in ['dynamic_programming', 'memoized_recursion']:
            domains.extend(['optimization', 'counting', 'shortest_path'])
        if algo_class == 'greedy':
            domains.extend(['scheduling', 'knapsack', 'selection'])
        if analysis.get('uses_sorting'):
            domains.append('sorting_based')
        
        return list(set(domains))


